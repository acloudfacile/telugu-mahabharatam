def hair_jata(d, cy, r):  # sage bun
    d.ellipse([S/2-r-2,cy-r-8,S/2+r+2,cy-r+30], fill=(90,70,50))
    d.ellipse([S/2-22,cy-r-34,S/2+22,cy-r+2], fill=(90,70,50))
